import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import {mkdir,writeFile,readFile,readdir,rename} from 'node:fs/promises';
import {migrationFixture} from './helpers/migration-fixture.js';
import {listenForBrowser} from './helpers/http-server.js';
import {createApp} from '../src/server.mjs';
import {createWorkspaceService} from '../src/workspace.js';
import {createBatchService} from '../src/batches.js';
import {createInboxStrategy} from '../src/inbox.js';
import {createRestructureStrategy} from '../src/restructure.js';

test('公开工作台保存设置、重启复用、发现任务与分类，并拒绝失效路径和跨库设置',async t=>{
 const f=await migrationFixture(t),libraryPath=f.backup.originalPath;
 const sourceRoot=path.join(f.root,'inbox'),artifactRoot=path.join(f.root,'artifacts'),stateDirectory=path.join(f.root,'settings'),configPath=path.join(f.root,'config.json');
 await mkdir(sourceRoot);await mkdir(artifactRoot);await mkdir(path.join(libraryPath,'raw/sources/001 测试'));
 await writeFile(path.join(sourceRoot,'new.md'),'固定合成材料，无模型调用。');
 const configuration={llmConfig:{provider:'openai',model:'fixed-test',apiKey:'must-never-leak'},recentProjects:[{id:'original-uuid',path:libraryPath}]};
 await writeFile(configPath,JSON.stringify(configuration));
 const input={libraryPath,sourceRoot,artifactRoot,wikiSourcePath:path.join(f.root,'upstream'),configPath};
 async function start(){
  const batches=createBatchService({stateDirectory:path.join(f.root,'batches'),strategies:{inbox:createInboxStrategy(),restructure:createRestructureStrategy()}});
  const server=createApp({batches,workspace:createWorkspaceService({batches,stateDirectory})});await listenForBrowser(server);
  t.after(()=>new Promise(resolve=>server.close(resolve)));
  const base=`http://127.0.0.1:${server.address().port}`;
  const {token}=await(await fetch(base+'/api/session')).json();
  return {base,server,request:async(action,data={})=>{const response=await fetch(base+'/api/'+action,{method:'POST',headers:{'Content-Type':'application/json','X-Organizer-Token':token},body:JSON.stringify(data)});return {status:response.status,body:await response.json()};}};
 }
 const first=await start();
 const empty=await first.request('workspace/list');assert.deepEqual(empty.body.libraries,[]);
 const saved=await first.request('workspace/save',input);assert.equal(saved.status,200);assert.equal(saved.body.valid,true);
 const record=saved.body;assert.ok(!JSON.stringify(record).includes('must-never-leak'));
 const id=record.id;
 const created=await first.request('workspace/create',{id,mode:'inbox',libraryPath:'/ignored-client-value'});assert.equal(created.status,200);assert.equal(created.body.libraryPath,libraryPath);assert.equal(created.body.counts.total,1);
 const batchId=created.body.batchId;
 await new Promise(resolve=>first.server.close(resolve));
 const second=await start();
 const restored=await second.request('workspace/list');assert.equal(restored.body.libraries[0].id,id);assert.equal(restored.body.libraries[0].valid,true);
 const tasks=await second.request('batches/list');assert.equal(tasks.body.records[0].batchId,batchId);
 const task=await second.request('batches/get',{batchId});assert.equal(task.body.phase,'analysis');
 const categories=await second.request('workspace/categories',{id});assert.ok(categories.body.categories.some(item=>item.path==='001 测试'));assert.ok(categories.body.files.some(item=>item.name==='old.md'));
 const deep='900 父级/100.20 子类/深层',rawRoot=path.join(libraryPath,'raw/sources');
 await mkdir(path.join(rawRoot,deep),{recursive:true});await mkdir(path.join(rawRoot,'空分类'));
 await writeFile(path.join(rawRoot,deep,'.category.json'),JSON.stringify({description:'实际深层说明'}));
 for(let i=0;i<53;i++)await writeFile(path.join(rawRoot,deep,`材料${String(i).padStart(2,'0')}.md`),'合成分页材料');
 const firstPage=await second.request('workspace/categories',{id,category:deep});
 assert.equal(firstPage.body.total,53);assert.equal(firstPage.body.files.length,50);assert.equal(firstPage.body.nextCursor,50);
 assert.equal(firstPage.body.categories.find(item=>item.path===deep).description,'实际深层说明');
 const lastPage=await second.request('workspace/categories',{id,category:deep,cursor:firstPage.body.nextCursor});
 assert.equal(lastPage.body.files.length,3);assert.equal(lastPage.body.nextCursor,null);
 assert.equal(new Set([...firstPage.body.files,...lastPage.body.files].map(file=>file.path)).size,53);
 assert.equal((await second.request('workspace/categories',{id,category:'空分类'})).body.total,0);
 assert.ok((await second.request('workspace/categories',{id})).body.files.some(file=>file.name==='old.md'));
 assert.equal((await fetch(second.base+'/category-browser.js')).status,200);assert.equal((await fetch(second.base+'/category-browser.css')).status,200);
 assert.equal((await second.request('workspace/categories',{id,category:'../wiki'})).status,400);
 const homeModule=await fetch(second.base+'/task-home.js');assert.equal(homeModule.status,200);assert.match(homeModule.headers.get('content-type'),/javascript/);
 const index=await(await fetch(second.base+'/')).text();assert.match(index,/分类浏览工作台/);assert.doesNotMatch(index,/示例材料|原型对比/);
 const continuation=await fetch(second.base+'/inbox?batchId='+batchId);assert.equal(continuation.status,200);
 const overlap=await second.request('workspace/save',{...input,artifactRoot:sourceRoot});assert.equal(overlap.body.code,'OVERLAPPING_PATHS');
 assert.equal((await second.request('workspace/save',{...input,artifactRoot:stateDirectory})).body.code,'OVERLAPPING_PATHS');
 assert.equal((await second.request('workspace/save',{...input,sourceRoot:path.join(libraryPath,'wiki')})).body.code,'INVALID_INBOX');
 assert.equal((await second.request('workspace/save',{...input,id:'00000000-0000-0000-0000-000000000000'})).body.code,'LIBRARY_MISMATCH');
 const stored=await readFile(path.join(stateDirectory,(await readdir(stateDirectory)).find(name=>name.endsWith('.json'))),'utf8');assert.ok(!stored.includes('must-never-leak'));
 const settingsFile=path.join(stateDirectory,id+'.json');
 await writeFile(settingsFile,stored.replace('original-uuid','tampered-project'));
 assert.equal((await second.request('workspace/list')).status,400);
 assert.equal((await second.request('workspace/create',{id,mode:'inbox'})).status,400);
 await writeFile(settingsFile,stored);
 assert.deepEqual(JSON.parse(await readFile(configPath,'utf8')),configuration);
 await rename(sourceRoot,sourceRoot+'-missing');
 assert.equal((await second.request('workspace/list')).body.libraries[0].valid,false);
 assert.equal((await second.request('workspace/create',{id,mode:'inbox'})).status,400);
 await rename(sourceRoot+'-missing',sourceRoot);
 await writeFile(path.join(libraryPath,'.llm-wiki/project.json'),JSON.stringify({id:'different-library'}));
 const changed=await second.request('workspace/list');assert.equal(changed.body.libraries[0].valid,false);assert.match(changed.body.libraries[0].error,/身份已变化/);
 assert.equal((await second.request('workspace/create',{id,mode:'restructure'})).body.code,'LIBRARY_CHANGED');
});
